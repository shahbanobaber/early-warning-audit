"""summary.md from metrics.json."""

from __future__ import annotations

from .evaluate import MODELS


def _pct(v: float) -> str:
    return f"{100 * v:.0f}%"


def _ci(ci) -> str:
    return f"[{100 * ci[0]:.0f}, {100 * ci[1]:.0f}]"


def _pts(v: float, ci) -> str:
    return f"{100 * v:+.0f} pts [{100 * ci[0]:+.0f}, {100 * ci[1]:+.0f}]"


def summary(result: dict, weeks_shown=(0, 2, 4, 6, 8, 10, 12, 16, 20)) -> str:
    st = result["settings"]
    b = str(st["main_budget"])
    rows = [r for r in result["by_week"] if r["week"] in weeks_shown]
    out = [
        "# Results",
        "",
        f"Generated by `python -m ewaudit run`. Trained on 2013B, 2013J and 2014B presentations, tested on "
        f"{st['test_presentation']}. A warning flags the top {_pct(st['main_budget'])} of students still enrolled "
        "at the end of each week. At risk = finished with Fail or Withdrawn.",
        "",
        "## By week",
        "",
        "| week | still enrolled | at risk among them | eventual at-risk already gone | AUC: "
        + " / ".join(MODELS.values()) + f" | precision at {_pct(st['main_budget'])} | recall | reached |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        m = r["models"][st["main"]]
        bm = m["budgets"][b]
        aucs = " / ".join(f"{r['models'][k]['auc']:.3f}" for k in MODELS)
        eventual = r["eventual_at_risk"]
        out.append(f"| {r['week']} | {r['n_test']:,} | {_pct(r['base_rate'])} | "
                   f"{r['already_gone']:,} of {eventual:,} ({_pct(r['already_gone'] / eventual)}) | "
                   f"{aucs} | {_pct(bm['precision'])} {_ci(m['ci']['precision'])} | {_pct(bm['recall'])} | "
                   f"{_pct(bm['reached_share'])} |")
    out += ["", "Precision and recall are among students still enrolled. Reached = flagged and at risk, as a share "
            "of every student in the cohort who ends up failing or withdrawing, including those already gone. "
            f"Intervals are 95% bootstrap intervals for {MODELS[st['main']]}.", ""]

    for w, a in result["audits"].items():
        out += [f"## Week {w}: errors by group ({MODELS[st['main']]})", "",
                "| group | students | at risk | flagged | missed (of at-risk) | gap vs rest | precision "
                "| false alarms |",
                "|---|---|---|---|---|---|---|---|"]
        for r in a["subgroups"]:
            gap = f"{100 * r['miss_gap']:+.1f} pts [{100 * r['miss_gap_ci'][0]:+.1f}, {100 * r['miss_gap_ci'][1]:+.1f}]"
            out.append(f"| {r['dimension']}: {r['group']} | {r['n']:,} | {_pct(r['at_risk'])} | {_pct(r['flagged'])} | "
                       f"{_pct(r['miss'])} {_ci(r['miss_ci'])} | {gap} | {_pct(r['precision'])} "
                       f"{_ci(r['precision_ci'])} | {_pct(r['false_alarm'])} |")
        lr = a["subgroups_logistic"]
        worst = max(lr, key=lambda r: abs(r["miss_gap"]))
        out += ["", f"With logistic regression instead, the largest miss-rate gap is {100 * worst['miss_gap']:+.1f} "
                f"points ({worst['dimension']}: {worst['group']}).", "",
                f"## Week {w}: what a missing trace means, by group", "",
                "| trace absent | group | share without it | at risk without | at risk with | difference "
                "| gap vs rest |",
                "|---|---|---|---|---|---|---|"]
        for r in a["missing_traces"]:
            diff, gap = _pts(r["difference"], r["difference_ci"]), _pts(r["gap"], r["gap_ci"])
            out.append(f"| {r['trace']} | {r['dimension']}: {r['group']} | {_pct(r['share_absent'])} | "
                       f"{_pct(r['risk_absent'])} | {_pct(r['risk_present'])} | {diff} | {gap} |")
        out += ["", f"## Week {w}: predicted against observed risk, by group", "",
                "The model never sees group membership. A positive gap means the group fails or withdraws more "
                "often than the model predicts for it.", "",
                "| group | students | observed at risk | mean predicted | observed minus predicted |",
                "|---|---|---|---|---|"]
        for r in a["calibration"]:
            out.append(f"| {r['dimension']}: {r['group']} | {r['n']:,} | {_pct(r['observed'])} | "
                       f"{_pct(r['predicted'])} | {_pts(r['under'], r['under_ci'])} |")
        out += ["", f"## Week {w}: AUC by module", "", "| " + " | ".join(a["auc_by_module"]) + " |",
                "|" + "---|" * len(a["auc_by_module"]),
                "| " + " | ".join(f"{v:.3f}" for v in a["auc_by_module"].values()) + " |", "",
                f"## Week {w}: which traces carry the warning", "",
                "Drop in AUC when one family of traces is shuffled across students, mean of 5 shuffles. Families "
                "overlap, so a small drop means the family adds little on top of the others, not that it is "
                "unrelated to the outcome.", "", "| traces | AUC drop |", "|---|---|"]
        for fam, (mean, sd) in sorted(a["importance"].items(), key=lambda kv: -kv[1][0]):
            out.append(f"| {fam} | {mean:.3f} (sd {sd:.3f}) |")
        out.append("")
    return "\n".join(out)
